// Operadores Aritméticos

let a = 2
let b = 9 

console.log(a + b) // Soma
console.log(a - b) // Subtração
console.log( a * b) // Multiplicação
console.log(a / b) // Divisão 
console.log(a % b) // Modulo ou Resto da divisão
console.log(a ** b) // Potência

// Operadores de comparação

console.log("\n--- Operadores de Comparação ---")

let c = 7
let d = 8

console.log(c == d) // Igual ou comparação
console.log(c === d) // Igual (valor e tipo)
console.log(c != d) // Diferente
console.log(c !== d) // Diferente (valor e tipo)
console.log(c > d) // Maior
console.log(c >= d) // Maior/Igual
console.log(c < d) // Menor 
console.log(c <= d) // Menor/Igual 

